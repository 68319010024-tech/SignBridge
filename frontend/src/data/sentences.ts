// เรียงตามรูปแบบประโยค บอกเล่า → คำถาม → ปฏิเสธ (sort ของ JS คงลำดับเดิมไว้ในกลุ่มเดียวกัน)
const TYPE_ORDER: SentenceType[] = ['บอกเล่า', 'คำถาม', 'ปฏิเสธ'];
const byType = (list: SentenceExample[]) =>
  [...list].sort((a, b) => TYPE_ORDER.indexOf(a.type) - TYPE_ORDER.indexOf(b.type));

export const SENTENCES: Record<SentenceLength, SentenceExample[]> = {
  3: byType(SENTENCES_UNSORTED[3]),
  4: byType(SENTENCES_UNSORTED[4]),
};

// path แบบ relative (ไม่มี "/" นำหน้า) ให้ตรงกับ base: './' ใน vite.config.ts — ดูเหตุผลใน WordDetailPage
export const sentenceVideoSrc = (length: SentenceLength, s: SentenceExample) =>
  encodeURI(`video-sentence/${length}/${s.id}.mp4`);

export const sentenceText = (words: SentenceWord[]) => words.map((x) => x.word).join(' ');

// "ประธาน + กริยา + กรรม" จากหน้าที่ของคำแต่ละคำตามลำดับ
export const grammarPattern = (words: SentenceWord[]) => words.map((x) => x.role).join(' + ');

